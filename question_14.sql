-- This HackerRank problem asks you to:

-- Retrieve the name column from the Employee table.
-- Display only the employee names.
-- Sort the names in alphabetical order (ascending).
-- No filtering or conditions are required.
-- SQL Query
link="https://www.hackerrank.com/challenges/name-of-employees/problem?"
SELECT name
FROM Employee
ORDER BY name ASC;

-- ASC means ascending order, so the names will be displayed alphabetically.

